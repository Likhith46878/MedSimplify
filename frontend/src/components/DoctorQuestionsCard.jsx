import React, { useState } from 'react';
import { HelpCircle, Check, Copy, MessageSquarePlus } from 'lucide-react';

export default function DoctorQuestionsCard({ questions, onAskChatbot }) {
  const [copiedIndex, setCopiedIndex] = useState(null);
  const [allCopied, setAllCopied] = useState(false);

  if (!questions || questions.length === 0) return null;

  const handleCopySingle = (text, idx) => {
    navigator.clipboard.writeText(text);
    setCopiedIndex(idx);
    setTimeout(() => setCopiedIndex(null), 2000);
  };

  const handleCopyAll = () => {
    const formattedQuestions = questions
      .map((q, i) => `${i + 1}. ${q}`)
      .join('\n');
    navigator.clipboard.writeText(
      `Questions for My Doctor (Generated by MedSimplify):\n\n${formattedQuestions}`
    );
    setAllCopied(true);
    setTimeout(() => setAllCopied(false), 2500);
  };

  return (
    <div className="result-card doctor-questions-card">
      <div className="card-header-bar">
        <div className="card-header-icon icon-emerald">
          <HelpCircle size={18} />
        </div>
        <div className="card-header-title-wrap">
          <h3 className="card-section-title">Questions to Ask Your Doctor</h3>
          <span className="card-section-subtitle">
            Practical talking points for your next healthcare appointment
          </span>
        </div>
        <button
          type="button"
          className="btn-copy-all"
          onClick={handleCopyAll}
          title="Copy all questions to clipboard"
        >
          {allCopied ? <Check size={14} className="text-success" /> : <Copy size={14} />}
          <span>{allCopied ? 'Copied All!' : 'Copy All Questions'}</span>
        </button>
      </div>

      <div className="card-body">
        <div className="questions-list">
          {questions.map((q, idx) => (
            <div key={idx} className="question-item-row">
              <span className="question-idx-pill">{idx + 1}</span>
              <span className="question-content-text">{q}</span>
              <div className="question-action-btns">
                {onAskChatbot && (
                  <button
                    type="button"
                    className="btn-icon-subtle"
                    onClick={() => onAskChatbot(q)}
                    title="Ask MedSimplify AI about this"
                  >
                    <MessageSquarePlus size={15} />
                    <span className="sr-only">Ask AI</span>
                  </button>
                )}
                <button
                  type="button"
                  className="btn-icon-subtle"
                  onClick={() => handleCopySingle(q, idx)}
                  title="Copy question"
                >
                  {copiedIndex === idx ? (
                    <Check size={15} className="text-success" />
                  ) : (
                    <Copy size={15} />
                  )}
                  <span className="sr-only">Copy</span>
                </button>
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
