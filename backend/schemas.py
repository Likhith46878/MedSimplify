"""
Pydantic Schemas for MedSimplify Backend API
"""

from typing import List, Optional, Dict, Any, Literal
from pydantic import BaseModel, Field


class OverviewSchema(BaseModel):
    sections_detected: str = Field(
        description="Names of major test sections detected (e.g. 'Complete Blood Count & Metabolic Panel')"
    )
    total_tests_analyzed: int = Field(
        description="Total number of discrete test results identified in the report"
    )
    important_findings_count: int = Field(
        description="Number of findings that fall outside standard reference ranges or warrant attention"
    )
    status: str = Field(
        description="General patient-friendly status descriptor (e.g. 'Review Recommended', 'All Standard Values Normal')"
    )


class ImportantFindingSchema(BaseModel):
    title: str = Field(
        description="Name of the test or finding (e.g. 'HbA1c (Average Blood Sugar)')"
    )
    value: str = Field(
        description="Reported value and unit as stated in the report (e.g. '6.1 %')"
    )
    explanation: str = Field(
        description="Plain-English explanation of what this test means and how it compares to the report target"
    )
    importance: Literal["high", "moderate", "low"] = Field(
        default="moderate",
        description="Priority level of the finding based strictly on report reference ranges"
    )


class KeyValueSchema(BaseModel):
    test: str = Field(
        description="Name of the medical test (e.g. 'Hemoglobin', 'Fasting Glucose')"
    )
    value: str = Field(
        description="Numerical or qualitative result (e.g. '13.2', '108')"
    )
    unit: str = Field(
        default="",
        description="Unit of measurement from report (e.g. 'g/dL', 'mg/dL', '%')"
    )
    reference_range: str = Field(
        default="Not provided in report",
        description="Reference target or healthy range printed on the report (e.g. '13.0 - 17.0 g/dL')"
    )
    explanation: str = Field(
        description="Brief plain-language description explaining whether this is normal/elevated and what it measures"
    )


class AIAnalysisReport(BaseModel):
    """Structured report analysis generated by Gemini."""
    overview: OverviewSchema
    summary: str = Field(
        description="Clear, 2-4 sentence plain-English overview of the entire medical report for the patient."
    )
    important_findings: List[ImportantFindingSchema] = Field(
        default_factory=list,
        description="List of significant or out-of-range findings from the report. Empty if all normal."
    )
    key_values: List[KeyValueSchema] = Field(
        default_factory=list,
        description="Structured table of all key lab test values found in the report."
    )
    what_this_means: str = Field(
        description="Synthesized educational interpretation connecting the results in simple terms without diagnosing."
    )
    doctor_questions: List[str] = Field(
        default_factory=list,
        description="3 to 5 clear, patient-empowering questions to discuss with their doctor."
    )


class ReportResponse(BaseModel):
    """Full API response returned to the frontend."""
    filename: str
    file_type: str
    file_size: str
    analyzed_at: str
    extracted_text: str
    overview: OverviewSchema
    summary: str
    important_findings: List[ImportantFindingSchema]
    key_values: List[KeyValueSchema]
    what_this_means: str
    doctor_questions: List[str]


class ChatMessage(BaseModel):
    role: str = Field(description="'user' or 'assistant'")
    content: str = Field(description="Message text")


class ChatRequest(BaseModel):
    report_text: str = Field(default="", description="Full extracted text of the currently analyzed report")
    user_question: str = Field(description="Question asked by the patient")
    conversation_history: Optional[List[Dict[str, str]]] = Field(
        default=None,
        description="Optional recent conversation turns"
    )


class ChatbotResponseSchema(BaseModel):
    answer: str
    based_on_report: bool
    relevant_values: List[Dict[str, Any]] = Field(default_factory=list)
    safety_note: str
